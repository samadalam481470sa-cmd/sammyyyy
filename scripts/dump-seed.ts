/**
 * Writes server/db/seed.sql from the TypeScript seeder so GitHub holds the
 * permanent CRM database as reviewable SQL (not a binary sqlite file).
 *
 * Usage: npm run db:dump
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outPath = path.join(root, 'server/db/seed.sql')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'nwp-seed-'))
const dbPath = path.join(tmp, 'newport-crm.db')

process.env.CRM_DB_PATH = dbPath

const { db } = await import('../server/db/index.ts')

const SEEDED_AT = '2026-01-01 00:00:00'
const tables = db
  .prepare(`SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'`)
  .all() as { name: string }[]
for (const { name } of tables) {
  const cols = db.prepare(`PRAGMA table_info(${JSON.stringify(name)})`).all() as { name: string }[]
  const names = new Set(cols.map((c) => c.name))
  if (names.has('created_at')) {
    db.prepare(`UPDATE ${JSON.stringify(name)} SET created_at = ?`).run(SEEDED_AT)
  }
  if (names.has('updated_at')) {
    db.prepare(`UPDATE ${JSON.stringify(name)} SET updated_at = ?`).run(SEEDED_AT)
  }
}

db.close()

const dump = execFileSync('sqlite3', [dbPath, '.dump'], { encoding: 'utf8' })
const inserts = dump.split('\n').filter((line) => {
  if (!line.startsWith('INSERT INTO')) return false
  const table = line.slice('INSERT INTO '.length).split(' ')[0] ?? ''
  if (table.includes('sqlite_')) return false
  return true
})

if (inserts.length === 0) {
  throw new Error('db:dump produced no INSERT statements')
}

const header = `-- Canonical Newport Specialty Partners CRM demo database
-- Dataset: anon-letter-v1
-- GitHub source of truth together with server/db/schema.sql
-- Generated by npm run db:dump from src/data/mock*.ts and server/db/index.ts
-- Restore: sqlite3 data/newport-crm.db < server/db/schema.sql && sqlite3 data/newport-crm.db < server/db/seed.sql
-- Do not hand-edit. Runtime data/*.db files stay gitignored.

PRAGMA foreign_keys = OFF;
BEGIN TRANSACTION;
${inserts.join('\n')}
COMMIT;
PRAGMA foreign_keys = ON;
`

fs.writeFileSync(outPath, `${header}\n`)
fs.rmSync(tmp, { recursive: true, force: true })
console.log(`Wrote ${inserts.length} INSERT statements to ${path.relative(root, outPath)}`)
