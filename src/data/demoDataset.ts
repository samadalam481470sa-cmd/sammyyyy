/** Dates are generated relative to load time so the demo never goes stale. */
function daysFromNow(days: number, hour = 16): IsoDateTime {
  const date = new Date();
  date.setDate(date.getDate() + days);
  date.setHours(hour, 0, 0, 0);
  return date.toISOString();
}

function hoursAgo(hours: number): IsoDateTime {
  const date = new Date();
  date.setHours(date.getHours() - hours, 0, 0, 0);
  return date.toISOString();
}

