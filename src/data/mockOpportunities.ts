import type { Opportunity } from '@/types'
import {
  anonymousEntityName,
  anonymousProjectName,
  demoProjectNumber,
} from '../lib/demoAliases'

/**
 * Public demo opportunities.
 * Code names, entities, and round financials are synthetic sample data for
 * illustration only — they are not live targets or Newport operating metrics.
 */
type DealSeed = Omit<Opportunity, 'id' | 'projectName' | 'entityName' | 'projectNumber'>

function deal(id: string, rest: DealSeed): Opportunity {
  return {
    id,
    projectNumber: demoProjectNumber(id),
    projectName: anonymousProjectName(id),
    entityName: anonymousEntityName(id),
    ...rest,
  }
}

